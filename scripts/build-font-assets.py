"""Build self-hosted fonts from verified sources; never install or fetch fonts.

Run with Python 3.13 + fontTools 4.61.1 + Brotli 1.2.0. Set PYTHONPATH to
the isolated Brotli directory for this command only. Inputs are explicit:
  python scripts/build-font-assets.py --noto FILE --geist FILE \
    --noto-license FILE --geist-license FILE --receipt-dir PRIVATE_DIRECTORY
Noto common = source cmap below U+3400 plus standard GB2312 level-one Han;
the remainder uses 1024-codepoint windows. Every source cmap/UVS entry stays.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path
import platform
import sys

import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
GENERATOR = "scripts/build-font-assets.py"
NAMES = {
    "noto": {
        "family": "Wiki Noto SC",
        "commit": "6c1dbe27dcf7d817d4b62cec033ba77fa8e2a5ec",
        "url": "https://raw.githubusercontent.com/google/fonts/6c1dbe27dcf7d817d4b62cec033ba77fa8e2a5ec/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf",
        "sha256": "a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da",
    },
    "geist": {
        "family": "Wiki Geist",
        "commit": "2e554ff2ea3979b63afe770af6424eb8b9490a74",
        "url": "https://raw.githubusercontent.com/vercel/geist-font/2e554ff2ea3979b63afe770af6424eb8b9490a74/fonts/Geist/webfonts/Geist%5Bwght%5D.woff2",
        "sha256": "2ffebe993e969069a9789d15164b7715d42491b5835516c5e3b935d5f81b05f1",
    },
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


def write_identical_or_new(path, data):
    """Hashed assets and licenses are immutable, including on subsequent runs."""
    if path.exists():
        if not path.is_file() or path.read_bytes() != data:
            raise RuntimeError(f"Refusing to overwrite existing file: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as handle:
        handle.write(data)


def unicode_range(points):
    values = sorted(points)
    ranges = []
    for cp in values:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ",".join(f"U+{lo:X}" + (f"-{hi:X}" if hi != lo else "") for lo, hi in ranges)


def uvs(font):
    result = {}
    for table in font["cmap"].tables:
        if table.format == 14:
            for selector, entries in table.uvsDict.items():
                for base, glyph in entries:
                    result[(selector, base)] = glyph
    return result


def axis(font):
    return [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in font["fvar"].axes]


def encode(font):
    font.flavor = "woff2"
    font.recalcTimestamp = False
    stream = io.BytesIO()
    font.save(stream, reorderTables=True)
    return stream.getvalue()


def load(data):
    return TTFont(io.BytesIO(data), recalcTimestamp=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("noto", "geist", "noto-license", "geist-license", "receipt-dir"):
        parser.add_argument("--" + name, required=True, type=Path)
    args = parser.parse_args()
    public = ROOT / "public"
    output = public / "fonts"
    receipt = args.receipt_dir.resolve()
    if receipt == public or public in receipt.parents:
        raise RuntimeError("Private conversion receipts must be outside public")
    css_path = public / "fonts.css"
    manifest_path = output / "manifest.json"
    if manifest_path.exists():
        old = json.loads(manifest_path.read_text(encoding="utf-8"))
        if old.get("generator") != GENERATOR:
            raise RuntimeError("Existing manifest is not owned by this generator")
    if css_path.exists() and not css_path.read_text(encoding="utf-8").startswith("/* Generated by " + GENERATOR):
        raise RuntimeError("Existing fonts.css is not owned by this generator")

    inputs = {}
    for key in NAMES:
        path = getattr(args, key)
        inputs[key] = path.read_bytes()
        if sha(inputs[key]) != NAMES[key]["sha256"]:
            raise RuntimeError(f"Source hash mismatch: {key}")
    source = load(inputs["noto"])
    source_cmap = source.getBestCmap()
    source_uvs = uvs(source)
    source_axis = axis(source)
    if len(source_cmap) != 30890 or len(source_uvs) != 25:
        raise RuntimeError("Unexpected verified Noto coverage")
    baseline = encode(source)
    roundtrip = load(baseline)
    assert roundtrip.getBestCmap() == source_cmap
    assert uvs(roundtrip) == source_uvs
    assert axis(roundtrip) == source_axis
    baseline_name = f"noto-full-{sha(baseline)[:12]}.woff2"
    write_identical_or_new(receipt / baseline_name, baseline)

    gb_level_one = set()
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                gb_level_one.add(ord(bytes([lead, trail]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    common = {cp for cp in source_cmap if cp < 0x3400 or cp in gb_level_one}
    groups = {"common": common}
    for cp in sorted(set(source_cmap) - common):
        groups.setdefault(f"u{cp // 1024 * 1024:05x}", set()).add(cp)

    files = []
    geist = load(inputs["geist"])
    if not any(a[0] == "wght" and a[1] == 100 and a[3] == 900 for a in axis(geist)):
        raise RuntimeError("Unexpected Geist weight axis")
    geist_file = f"fonts/geist-{sha(inputs['geist'])[:12]}.woff2"
    write_identical_or_new(public / geist_file, inputs["geist"])
    files.append(dict(family="Wiki Geist", style="normal", weight="100 900",
                      file=geist_file, sha256=sha(inputs["geist"]), size=len(inputs["geist"]),
                      unicodeRange=unicode_range(geist.getBestCmap())))
    covered = set()
    covered_uvs = {}
    shard_receipts = []
    for name, points in groups.items():
        font = load(inputs["noto"])
        expected_uvs = {key: value for key, value in source_uvs.items() if key[1] in points}
        selectors = {key[0] for key in expected_uvs}
        options = subset.Options()
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.glyph_names = True
        options.recalc_timestamp = False
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=points | selectors)
        worker.subset(font)
        # The input uses post format 3: its synthetic glyph names change after
        # renumbering. Store those names explicitly for exact UVS comparison.
        font["post"].formatType = 2.0
        font["post"].extraNames = []
        font["post"].mapping = {}
        data = encode(font)
        check = load(data)
        actual = check.getBestCmap()
        assert set(actual) == points, f"cmap mismatch: {name}"
        assert all(actual[cp] == source_cmap[cp] for cp in points), f"glyph mismatch: {name}"
        assert uvs(check) == expected_uvs, f"UVS mismatch: {name}"
        assert axis(check) == source_axis, f"weight axis mismatch: {name}"
        assert all(table in check for table in ("GSUB", "GPOS", "gvar", "STAT")), name
        assert not covered.intersection(points), f"overlapping cmap: {name}"
        covered.update(points)
        covered_uvs.update(uvs(check))
        filename = f"fonts/noto-sc-{name}-{sha(data)[:12]}.woff2"
        write_identical_or_new(public / filename, data)
        files.append(dict(family="Wiki Noto SC", style="normal", weight="100 900",
                          file=filename, sha256=sha(data), size=len(data),
                          unicodeRange=unicode_range(points | selectors)))
        shard_receipts.append(dict(file=filename, codepoints=len(points), uvs=len(expected_uvs),
                                   size=len(data), sha256=sha(data)))
        print(f"{name}: {len(points)} codepoints, {len(data)} bytes", flush=True)
    assert covered == set(source_cmap), "Incomplete source cmap union"
    assert covered_uvs == source_uvs, "Incomplete source UVS union"
    licenses = []
    for key in NAMES:
        relative = f"fonts/OFL-{key}.txt"
        license_data = getattr(args, key + "_license").read_bytes()
        if b"SIL OPEN FONT LICENSE" not in license_data.upper():
            raise RuntimeError(f"Missing OFL license: {key}")
        write_identical_or_new(public / relative, license_data)
        licenses.append(relative)
    coverage = dict(sourceCmap=len(source_cmap), shardCmapUnion=len(covered), sourceUVS=len(source_uvs),
                    shardUVSUnion=len(covered_uvs), cmapComplete=True, uvsComplete=True,
                    commonCodepoints=len(common), notoShards=len(groups),
                    strategy="GB2312 level-one plus source cmap below U+3400; remainder in 1024-codepoint windows; UVS follows base",
                    weightAxis=source_axis)
    manifest = dict(schemaVersion=1, generator=GENERATOR, files=files,
                    sources=[dict(family=value["family"], url=value["url"], commit=value["commit"],
                                  sha256=value["sha256"]) for value in NAMES.values()],
                    coverage=coverage, licenses=licenses)
    css = [f"/* Generated by {GENERATOR}; complete source coverage, lazy Unicode shards. */"]
    for item in files:
        css.append("@font-face{" + f"font-family:'{item['family']}';font-style:{item['style']};"
                   + f"font-weight:{item['weight']};font-display:swap;src:url('/{item['file']}') format('woff2');"
                   + f"unicode-range:{item['unicodeRange']};" + "}")
    css_data = ("\n".join(css) + "\n").encode()
    # The ownership checks above permit updating only these generated indexes.
    output.mkdir(parents=True, exist_ok=True)
    manifest_path.write_bytes(json_bytes(manifest))
    css_path.write_bytes(css_data)
    tools = dict(python=platform.python_version(), pythonExecutable=sys.executable,
                 fontTools=fontTools.__version__, brotli=brotli.__version__)
    private = dict(generator=GENERATOR, tools=tools,
                   scriptSHA256=sha(Path(__file__).read_bytes()),
                   options=dict(layoutFeatures=["*"], nameIDs=["*"], nameLanguages=["*"],
                                glyphNames=True, postFormat=2, recalcTimestamp=False,
                                common="GB2312 B0-D7 / A1-FE plus source cmap below U+3400",
                                remainderWindow=1024, uvs="follow base, include selector"),
                   inputs={key: dict(path=str(getattr(args, key).resolve()), sha256=sha(data), size=len(data))
                           for key, data in inputs.items()},
                   baseline=dict(file=baseline_name, sha256=sha(baseline), size=len(baseline)),
                   coverage=coverage, shards=shard_receipts,
                   outputBytes=sum(item["size"] for item in files), cssSHA256=sha(css_data))
    receipt.mkdir(parents=True, exist_ok=True)
    (receipt / "font-assets-receipt.json").write_bytes(json_bytes(private))
    print(json.dumps(dict(status="PASS", **coverage, outputBytes=private["outputBytes"]), ensure_ascii=False))


if __name__ == "__main__":
    main()
